    is_x86 = detect_arch(client, ep)
    arch_label = "x86" if is_x86 else "x64"
    print(f"[*] Detected architecture: {{arch_label}}")

    # Read first bytes at EP
    first_bytes = client.read_memory(ep, 4)
    print(f"[*] First bytes at EP: {{first_bytes.hex()}}")

    if first_bytes[0] == 0x60:
        # pushad (x86): pushes EAX,ECX,EDX,EBX,ESP,EBP,ESI,EDI = 8×4 = 32 bytes
        print("[+] Detected pushad — x86 ESP-law compatible packer")
        esp = client.get_register("esp")
        hwbp_addr = esp - 0x20
        print(f"[*] Setting hardware read+write BP on ESP-0x20: {{hwbp_addr:#x}} (waiting for popad)")
        # popad READS from stack, so use "rw" (read+write) not "w" (write-only)
        client.set_hardware_breakpoint(hwbp_addr, "rw")

    elif first_bytes[0] == 0x9C:
        # pushfd/pushfq
        print("[+] Detected pushfd/pushfq — stack-save packer")
        if is_x86:
            esp = client.get_register("esp")
            hwbp_addr = esp - 4
        else:
            rsp_addr = client.get_register("rsp")
            hwbp_addr = rsp_addr - 8
        client.set_hardware_breakpoint(hwbp_addr, "rw")
        print(f"[*] Hardware BP set at: {{hwbp_addr:#x}}")

    else:
        print("[*] No pushad/pushfd detected. Searching for OEP jump patterns...")
        try:
            vp = client.evaluate_expression("VirtualProtect")
            client.set_breakpoint(vp)
            print(f"    BP set: VirtualProtect @ {{vp:#x}}")
        except Exception:
            print("    VirtualProtect not found, relying on step-tracing")

    print("[*] Running... (this may take a while)")
    hit_count = 0
    reg_ip = "eip" if is_x86 else "rip"
    reg_sp = "esp" if is_x86 else "rsp"

    while hit_count < 50:
        client.go()
        client.wait_until_stopped()
        hit_count += 1
        ip_val = client.get_register(reg_ip)
        sp_val = client.get_register(reg_sp)
        print(f"    [{{hit_count}}] {{reg_ip.upper()}}={{ip_val:#x}} {{reg_sp.upper()}}={{sp_val:#x}}")

        # Read code at current position
        code = client.read_memory(ip_val, 8)

        # E9 = jmp rel32 (5 bytes): E9 xx xx xx xx
        if code[0] == 0xE9:
            target_off = struct.unpack_from("<i", code, 1)[0]
            target = ip_val + 5 + target_off  # 5-byte instruction
            print(f"    Possible OEP via JMP rel32 -> {{target:#x}}")

        # EB = jmp rel8 (2 bytes): EB xx
        elif code[0] == 0xEB:
            target_off = struct.unpack_from("<b", code, 1)[0]
            target = ip_val + 2 + target_off  # 2-byte instruction
            print(f"    Possible OEP via JMP rel8 -> {{target:#x}}")

