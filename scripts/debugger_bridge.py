# ── Template rendering ──────────────────────────────────────────────────────────

def render_template(template_name: str, target_path: str) -> str:
    """Fill in a template with target-specific values."""
    tpl = TEMPLATES[template_name]
    target = Path(target_path)
    return tpl["script"].format(
        target_name=target.name,
        target_path=str(target.resolve()),
        target_stem=target.stem,
    )


def list_templates() -> str:
    """Markdown listing of all available templates."""
    lines = [
        "# Debugger Bridge Templates",
        f"Generated UTC: {datetime.now(timezone.utc).isoformat()}",
        "",
        "| Template | Title | Requires |",
        "|---|---|---|",
    ]
    for name, tpl in TEMPLATES.items():
        reqs = ", ".join(tpl["requires"])
        lines.append(f"| `{name}` | {tpl['title']} | {reqs} |")
    lines += ["", "## Usage",
              "python debugger_bridge.py generate <template> --target <binary> --out <output.py>",
              "Then run the generated script with x64dbg Automate installed.",
              ""]
    return "\n".join(lines)


# ── Main ──────────────────────────────────────────────────────────────────────────

def main() -> int:
    parser = argparse.ArgumentParser(
        description="x64dbg Automate 调试器桥接模板生成器",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""Examples:
  python debugger_bridge.py list
  python debugger_bridge.py generate anti_debug_bypass --target target.exe
  python debugger_bridge.py generate memory_dump --target packed.exe --out dump_script.py""",
    )
    sub = parser.add_subparsers(dest="command", help="Subcommand")

    sub.add_parser("list", help="List all available templates")

    p_gen = sub.add_parser("generate", help="Generate a debugger automation script")
    p_gen.add_argument("template", choices=list(TEMPLATES.keys()),
                       help="Template name")
    p_gen.add_argument("--target", required=True, help="Path to target binary")
    p_gen.add_argument("--out", help="Output path for generated script")

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        return 1

    if args.command == "list":
        print(list_templates())
        return 0

    if args.command == "generate":
        tpl = TEMPLATES[args.template]
        script = render_template(args.template, args.target)
        out_path = args.out or f"{args.template}_{Path(args.target).stem}.py"

        out_file = Path(out_path)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        out_file.write_text(script, encoding="utf-8")
        print(f"Generated: {out_path}")
        print(f"Template: {tpl['title']}")
        print(f"Requires: {', '.join(tpl['requires'])}")
        print(f"Target: {args.target}")
        print()
        print("Next steps:")
        print(f"  1. Install x64dbg: https://github.com/x64dbg/x64dbg")
        print(f"  2. Install x64dbg_automate: pip install x64dbg-automate")
        print(f"  3. Run: python {out_path}")
        return 0

    parser.print_help()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
